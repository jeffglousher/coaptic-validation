//! Target-native Response layouts only; no workload or performance timing.
#[cfg(not(test))]
fn main() {}

#[cfg(test)]
mod response_location_layout {
    use coaptic::app::{INLINE_PAYLOAD, LOCATION_MAX, ResponseError};
    use coaptic::message::{
        Code, ContentFormat, Echo, MessageId, OwnedToken, ParsedMessage, Token, TokenDecodeError,
        Type, extended,
    };
    use coaptic::{Endpoint, Response};

    #[derive(Clone, Copy, Debug, Default, Eq, PartialEq, Hash)]
    struct TinyToken {
        bytes: [u8; 1],
        len: u8,
    }

    impl OwnedToken for TinyToken {
        const EMPTY: Self = Self { bytes: [0], len: 0 };
        const MAX_LEN: usize = 1;
        fn try_from_bytes(bytes: &[u8]) -> Result<Self, extended::CapacityError> {
            let mut token = Self::try_zeroed(bytes.len())?;
            token.as_bytes_mut().copy_from_slice(bytes);
            Ok(token)
        }
        fn try_zeroed(len: usize) -> Result<Self, extended::CapacityError> {
            if len > Self::MAX_LEN {
                return Err(extended::CapacityError {
                    required: len,
                    available: Self::MAX_LEN,
                });
            }
            Ok(Self {
                bytes: [0],
                len: len as u8,
            })
        }
        fn as_bytes_mut(&mut self) -> &mut [u8] {
            &mut self.bytes[..usize::from(self.len)]
        }
        fn as_bytes(&self) -> &[u8] {
            &self.bytes[..usize::from(self.len)]
        }
    }

    // Exact field types and payload variants from accepted c655b3a Response.
    // Both core arms execute this mirror comparison on the actual MSVC target.
    #[allow(dead_code)]
    #[derive(Clone, Copy)]
    enum LegacyPayload<'a> {
        Empty,
        Static(&'static [u8]),
        Inline {
            bytes: [u8; INLINE_PAYLOAD],
            len: u16,
        },
        /// Catalog or other generated bytes that outlive this [`Response`]
        /// (poll / [`LinkFormatScratch`](super::LinkFormatScratch)). Not an
        /// owned 4KiB field.
        Borrowed(&'a [u8]),
    }
    #[allow(dead_code)]
    struct LegacyResponse<'a, T: OwnedToken = Token> {
        invalid: Option<ResponseError>,
        received_header: Option<ParsedMessage<'a, T>>,
        received_at_ms: Option<u64>,
        code: Code,
        payload: LegacyPayload<'a>,
        content_format: Option<ContentFormat>,
        etag: [u8; 8],
        etag_len: u8,
        max_age: Option<u32>,
        observe: Option<u32>,
        ty: Option<Type>,
        token: Option<T>,
        mid: Option<MessageId>,
        peer: Option<Endpoint>,
        assembled: Option<&'a [u8]>,
        echo: Option<Echo>,
        location_path: [&'a str; LOCATION_MAX],
        location_path_len: u8,
        location_query: [&'a str; LOCATION_MAX],
        location_query_len: u8,
        separate: bool,
        deferred: bool,
        fresh_piv: bool,
        /// Length of the source before [`INLINE_PAYLOAD`] / [`RESPONSE_BODY`]
        /// copy. Greater than [`Self::payload`] when truncated.
        payload_src_len: usize,
    }

    fn layout<X, Y>(role: &str) {
        if role == "baseline" {
            assert_eq!(
                core::mem::size_of::<X>(),
                core::mem::size_of::<Y>(),
                "baseline size for {}",
                core::any::type_name::<X>()
            );
        } else {
            assert_eq!(role, "candidate", "unknown layout role");
            assert!(
                core::mem::size_of::<X>() <= core::mem::size_of::<Y>(),
                "candidate growth for {}",
                core::any::type_name::<X>()
            );
        }
        assert_eq!(
            core::mem::align_of::<X>(),
            core::mem::align_of::<Y>(),
            "alignment for {}",
            core::any::type_name::<X>()
        );
    }

    fn same_layout<T: OwnedToken>(role: &str) {
        layout::<Response<'_, T>, LegacyResponse<'_, T>>(role);
        layout::<Option<Response<'_, T>>, Option<LegacyResponse<'_, T>>>(role);
        layout::<
            Result<Response<'_, T>, ResponseError>,
            Result<LegacyResponse<'_, T>, ResponseError>,
        >(role);
        layout::<
            Result<Option<Response<'_, T>>, ResponseError>,
            Result<Option<LegacyResponse<'_, T>>, ResponseError>,
        >(role);
        layout::<
            Option<Result<Response<'_, T>, ResponseError>>,
            Option<Result<LegacyResponse<'_, T>, ResponseError>>,
        >(role);
        layout::<
            Result<Response<'_, T>, TokenDecodeError>,
            Result<LegacyResponse<'_, T>, TokenDecodeError>,
        >(role);
    }

    #[test]
    fn response_and_wrappers_preserve_baseline_layout() {
        let role = match std::env::var("COAPTIC_RESPONSE_LAYOUT_ROLE") {
            Ok(role) => role,
            Err(std::env::VarError::NotPresent) => "candidate".into(),
            Err(error) => panic!("invalid layout role: {error}"),
        };
        assert!(
            matches!(role.as_str(), "baseline" | "candidate"),
            "unknown layout role"
        );
        assert_eq!(core::mem::size_of::<TinyToken>(), 2);
        same_layout::<Token>(&role);
        same_layout::<TinyToken>(&role);
        same_layout::<extended::Token<0>>(&role);
        same_layout::<extended::Token<1>>(&role);
        same_layout::<extended::Token<8>>(&role);
        same_layout::<extended::Token<16>>(&role);
        same_layout::<extended::Token<64>>(&role);
        same_layout::<extended::Token<512>>(&role);
    }
}
